/**
 * Cloudflare Pages (static) build step. Replaces what used to be server routes:
 *   public/_redirects            from data/redirects.json (was next.config redirects)
 *   public/icons/*.png           PWA icons (was app/icons/[size] route)
 *   public/og/<lang>/...png      OG cards (was app/og route)
 * Output goes to public/ (gitignored) so `next build` copies it into out/.
 */
import fs from "node:fs";
import path from "node:path";
import React from "react";
import { ImageResponse } from "next/og";
import redirects from "../data/redirects.json";
import pages from "../generated/pages.json";
import { CATEGORY_MAP, isCategory } from "../lib/categories";
import { SITE_NAME } from "../lib/site";

const PUB = path.join(process.cwd(), "public");
const write = (rel: string, data: string | Buffer) => {
  const p = path.join(PUB, rel);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, data);
};
const png = async (res: ImageResponse) => Buffer.from(await res.arrayBuffer());

/* ---------- _redirects (301, both languages) ---------- */
const lines: string[] = [];
for (const r of redirects.redirects) {
  for (const from of r.from) {
    lines.push(`/${r.category}/${from} /${r.category}/${r.to} 301`);
    lines.push(`/hi/${r.category}/${from} /hi/${r.category}/${r.to} 301`);
  }
}
write("_redirects", `# generated by scripts/build-static-assets.tsx\n${lines.join("\n")}\n`);

/* ---------- icons ---------- */
const ICONS: Record<string, { px: number; pad: number }> = { "180": { px: 180, pad: 0 }, "192": { px: 192, pad: 0 }, "512": { px: 512, pad: 0 }, "512-maskable": { px: 512, pad: 0.2 } };
async function icons() {
  for (const [name, cfg] of Object.entries(ICONS)) {
    const s = cfg.px, inner = s * (1 - cfg.pad * 2);
    const img = new ImageResponse(
      (
        <div style={{ width: s, height: s, display: "flex", alignItems: "center", justifyContent: "center", background: "#F28C0F", borderRadius: cfg.pad ? 0 : s / 2 }}>
          <div style={{ width: inner, height: inner, display: "flex", flexDirection: "column", alignItems: "center", justifyContent: "center" }}>
            <div style={{ width: inner * 0.22, height: inner * 0.34, background: "#FFF8EC", borderRadius: "50% 50% 50% 50% / 70% 70% 30% 30%", marginBottom: inner * 0.04 }} />
            <div style={{ width: inner * 0.56, height: inner * 0.22, background: "#8E1B2D", borderRadius: `0 0 ${inner * 0.3}px ${inner * 0.3}px` }} />
          </div>
        </div>
      ),
      { width: s, height: s },
    );
    write(`icons/${name}.png`, await png(img));
  }
}

/* ---------- OG cards ---------- */
const fontCache = new Map<string, ArrayBuffer>();
async function googleFont(family: string, weight: number, text: string): Promise<ArrayBuffer | null> {
  const key = `${family}:${weight}:${text}`;
  if (fontCache.has(key)) return fontCache.get(key)!;
  try {
    const css = await (await fetch(`https://fonts.googleapis.com/css2?family=${family}:wght@${weight}&text=${encodeURIComponent(text)}`)).text();
    const url = /src: url\((.+?)\) format\('(opentype|truetype)'\)/.exec(css)?.[1];
    if (!url) return null;
    const buf = await (await fetch(url)).arrayBuffer();
    fontCache.set(key, buf);
    return buf;
  } catch {
    return null;
  }
}

async function card(lang: "hinglish" | "hi", c?: string, title?: string) {
  const cat = c && isCategory(c) ? CATEGORY_MAP[c] : null;
  const t = title ?? (cat ? cat.name[lang] : lang === "hi" ? "आरती, पूजा विधि और पाठ" : "Aarti, Puja Vidhi aur Path");
  const eyebrow = cat ? cat.name[lang] : lang === "hi" ? "हिंदी और हिंग्लिश में" : "Hinglish aur Hindi mein";
  const accent = cat?.accent ?? "#F28C0F";
  const all = `${t}${eyebrow}${SITE_NAME}`;
  const fonts: { name: string; data: ArrayBuffer; weight: 700; style: "normal" }[] = [];
  const [deva, latin] = await Promise.all([googleFont("Noto+Sans+Devanagari", 700, all), googleFont("Inter", 700, all)]);
  if (deva) fonts.push({ name: "Deva", data: deva, weight: 700, style: "normal" });
  if (latin) fonts.push({ name: "Latin", data: latin, weight: 700, style: "normal" });
  return png(
    new ImageResponse(
      (
        <div style={{ width: 1200, height: 630, display: "flex", background: "#FFF8EC", fontFamily: "Latin, Deva" }}>
          <div style={{ width: 28, background: accent, display: "flex" }} />
          <div style={{ flex: 1, display: "flex", flexDirection: "column", justifyContent: "space-between", padding: "64px 72px" }}>
            <div style={{ display: "flex", fontSize: 34, color: accent, fontWeight: 700 }}>{eyebrow}</div>
            <div style={{ display: "flex", fontSize: t.length > 40 ? 64 : 78, lineHeight: 1.25, color: "#2B1A12", fontWeight: 700 }}>{t}</div>
            <div style={{ display: "flex", alignItems: "center", gap: 18 }}>
              <div style={{ width: 54, height: 54, borderRadius: 27, background: "#F28C0F", display: "flex" }} />
              <div style={{ display: "flex", fontSize: 38, color: "#8E1B2D", fontWeight: 700 }}>{SITE_NAME}</div>
            </div>
          </div>
        </div>
      ),
      { width: 1200, height: 630, fonts: fonts.length ? fonts : undefined },
    ),
  );
}

async function og() {
  const stamp = path.join(process.cwd(), "generated", "og-manifest.json");
  // Skip unchanged cards so repeat builds stay fast.
  const prev: Record<string, string> = fs.existsSync(stamp) ? JSON.parse(fs.readFileSync(stamp, "utf8")) : {};
  const next: Record<string, string> = {};
  const jobs: { rel: string; lang: "hinglish" | "hi"; c?: string; title?: string }[] = [];
  for (const lang of ["hinglish", "hi"] as const) {
    jobs.push({ rel: `og/${lang}/default.png`, lang });
    for (const k of Object.keys(CATEGORY_MAP)) jobs.push({ rel: `og/${lang}/${k}.png`, lang, c: k });
  }
  for (const p of pages) {
    if (p.lang !== "hinglish" && p.lang !== "hi") continue;
    jobs.push({ rel: `og/${p.lang}/${p.category}/${p.slug}.png`, lang: p.lang, c: p.category, title: p.title });
  }
  let made = 0;
  for (const j of jobs) {
    const key = `${j.lang}|${j.c ?? ""}|${j.title ?? ""}`;
    next[j.rel] = key;
    if (prev[j.rel] === key && fs.existsSync(path.join(PUB, j.rel))) continue;
    write(j.rel, await card(j.lang, j.c, j.title));
    made++;
  }
  fs.writeFileSync(stamp, JSON.stringify(next));
  console.log(`og: ${jobs.length} cards (${made} rendered)`);
}

(async () => {
  await icons();
  await og();
  console.log(`_redirects: ${lines.length} rules, icons: ${Object.keys(ICONS).length}`);
})();
